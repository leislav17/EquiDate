import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';

test('manual and published entries share tracking, marks and automatic advance',async()=>{
  const db=new PGlite();
  await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth;
    create table auth.users(id uuid primary key,raw_app_meta_data jsonb,banned_until timestamptz);
    create table events(id uuid primary key,end_date date,status text,discipline text);
    create table external_event_assignments(user_id uuid,event_id uuid,primary key(user_id,event_id));
    create table competition_classes(id uuid primary key,event_id uuid);
    create table start_list_versions(id uuid primary key,class_id uuid,entries jsonb,unique(class_id,id));
    create table start_lists(class_id uuid primary key,version_id uuid);
    grant select on events,competition_classes,start_lists,start_list_versions to anon,authenticated;`);
  for(const name of ['20261118151405_provisional_live_results.sql','20261119104700_live_results_two_phases.sql','20261119105343_live_tracking.sql','20261119230837_live_reorder.sql','20261120010000_manual_live_entries.sql','20261120020000_live_manual_order.sql','20261120130308_combined_live_tracking_order.sql','20261120163022_manual_live_tracking.sql']) await db.exec(readFileSync('supabase/migrations/'+name,'utf8'));
  const u='00000000-0000-0000-0000-000000000001',e='00000000-0000-0000-0000-000000000002',c='00000000-0000-0000-0000-000000000003',v='00000000-0000-0000-0000-000000000004',m='00000000-0000-0000-0000-000000000005';
  await db.query("insert into auth.users values($1,'{\"equidate_external\":true}',null)",[u]);
  await db.query("insert into events values($1,current_date,'published','jumping')",[e]);
  await db.query('insert into competition_classes values($1,$2)',[c,e]);
  await db.query('insert into external_event_assignments values($1,$2)',[u,e]);
  await db.query("insert into start_list_versions values($1,$2,'[{\"position\":1,\"category\":\"A\"},{\"position\":2,\"category\":\"A\"}]')",[v,c]);
  await db.query('insert into start_lists values($1,$2)',[c,v]);
  await db.query("insert into manual_live_entries(id,class_id,rider,horse,category) values($1,$2,'A','B','C')",[m,c]);
  await db.query('select equidate_set_combined_live_order($1,$2,$3,$4,0,$5)',[u,e,c,v,['p:1',`m:${m}`,'p:2']]);
  await db.query("select equidate_published_tracking_action($1,$2,$3,$4,1,'current')",[u,e,c,v]);
  await db.query('select equidate_save_published_combined($1,$2,$3,$4,1,0,42,null,null)',[u,e,c,v]);
  assert.equal((await db.query<{current_manual_id:string}>('select current_manual_id from manual_live_tracking')).rows[0].current_manual_id,m);
  assert.equal((await db.query<{current_position:number|null}>('select current_position from live_tracking')).rows[0].current_position,null);
  await db.query('select equidate_save_manual_combined($1,$2,$3,$4,$5,4,55,null,null)',[u,e,c,v,m]);
  assert.equal((await db.query<{current_position:number}>('select current_position from live_tracking')).rows[0].current_position,2);
  assert.equal((await db.query<{current_manual_id:string|null}>('select current_manual_id from manual_live_tracking')).rows[0].current_manual_id,null);
  await db.query("select equidate_manual_tracking_action($1,$2,$3,$4,'current')",[u,e,c,m]);
  assert.equal((await db.query<{current_position:number|null}>('select current_position from live_tracking')).rows[0].current_position,null);
  await db.query("select equidate_published_tracking_action($1,$2,$3,$4,2,'current')",[u,e,c,v]);
  assert.equal((await db.query<{current_manual_id:string|null}>('select current_manual_id from manual_live_tracking')).rows[0].current_manual_id,null);
  await assert.rejects(db.query("select equidate_manual_tracking_action($1,$2,$3,$4,'absent')",[u,e,c,m]));
  const m2='00000000-0000-0000-0000-000000000006';
  await db.query("insert into manual_live_entries(id,class_id,rider,horse,category) values($1,$2,'C','D','C')",[m2,c]);
  await db.query('select equidate_set_combined_live_order($1,$2,$3,$4,1,$5)',[u,e,c,v,['p:1',`m:${m2}`,'p:2',`m:${m}`]]);
  await db.query("select equidate_manual_tracking_action($1,$2,$3,$4,'current')",[u,e,c,m2]);
  await db.query("select equidate_manual_tracking_action($1,$2,$3,$4,'absent')",[u,e,c,m2]);
  assert.equal((await db.query<{current_position:number}>('select current_position from live_tracking')).rows[0].current_position,2);
  await db.query("select equidate_manual_tracking_action($1,$2,$3,$4,'restore')",[u,e,c,m2]);
  await db.query("select equidate_published_tracking_action($1,$2,$3,$4,2,'absent')",[u,e,c,v]);
  assert.equal((await db.query<{current_position:number|null}>('select current_position from live_tracking')).rows[0].current_position,null);
  await db.query('delete from start_lists where class_id=$1',[c]);
  await db.query("select equidate_manual_tracking_action($1,$2,$3,$4,'current')",[u,e,c,m2]);
  assert.equal((await db.query<{current_manual_id:string}>('select current_manual_id from manual_live_tracking')).rows[0].current_manual_id,m2);
  await db.query('delete from external_event_assignments where user_id=$1',[u]);
  await assert.rejects(db.query("select equidate_manual_tracking_action($1,$2,$3,$4,'current')",[u,e,c,m]));
  await db.exec('set role anon'); await assert.rejects(db.query("select equidate_manual_tracking_action($1,$2,$3,$4,'current')",[u,e,c,m])); await db.exec('reset role');
  await db.close();
});

