import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';

test('hiding one live class retains data, hides direct public reads and can be reversed',async()=>{
  const db=new PGlite();
  await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth;
    create table auth.users(id uuid primary key,raw_app_meta_data jsonb,banned_until timestamptz);
    create table events(id uuid primary key,end_date date,status text,discipline text);
    create table external_event_assignments(user_id uuid,event_id uuid,primary key(user_id,event_id));
    create table competition_classes(id uuid primary key,event_id uuid);
    create table start_list_versions(id uuid primary key,class_id uuid,entries jsonb,unique(class_id,id));
    create table start_lists(class_id uuid primary key,version_id uuid);
    grant select on events,competition_classes,start_lists,start_list_versions to anon,authenticated;`);
  for(const name of ['20261118151405_provisional_live_results.sql','20261119104700_live_results_two_phases.sql','20261119105343_live_tracking.sql','20261119230837_live_reorder.sql','20261120010000_manual_live_entries.sql','20261120020000_live_manual_order.sql','20261120130308_combined_live_tracking_order.sql','20261120163022_manual_live_tracking.sql','20261120124332_live_result_starts.sql','20261120170632_live_results_visibility.sql'])await db.exec(readFileSync('supabase/migrations/'+name,'utf8'));
  const u='00000000-0000-0000-0000-000000000001',e='00000000-0000-0000-0000-000000000002',c='00000000-0000-0000-0000-000000000003',v='00000000-0000-0000-0000-000000000004',m='00000000-0000-0000-0000-000000000005',c2='00000000-0000-0000-0000-000000000006';
  await db.query("insert into auth.users values($1,'{\"equidate_external\":true}',null)",[u]);
  await db.query("insert into events values($1,current_date,'published','jumping')",[e]);
  await db.query('insert into competition_classes values($1,$3),($2,$3)',[c,c2,e]);
  await db.query('insert into external_event_assignments values($1,$2)',[u,e]);
  await db.query("insert into start_list_versions values($1,$2,'[{\"position\":1,\"category\":\"A\"}]')",[v,c]);
  await db.query('insert into start_lists values($1,$2)',[c,v]);
  await db.query('insert into live_result_starts(class_id) values($1),($2)',[c,c2]);
  await db.query('insert into provisional_live_results(class_id,start_version_id,position,obstacle_faults,time_seconds) values($1,$2,1,4,55)',[c,v]);
  await db.query("insert into manual_live_entries(id,class_id,rider,horse,category) values($1,$2,'A','B','C')",[m,c]);
  await db.query('insert into live_tracking(class_id,start_version_id) values($1,$2)',[c,v]);
  await db.query('insert into manual_live_tracking(class_id) values($1)',[c]);
  await db.query('insert into live_combined_order(class_id,start_version_id) values($1,$2)',[c,v]);
  await db.query('insert into live_manual_only_order(class_id) values($1)',[c]);
  const toggle=(visible:boolean)=>db.query('select equidate_set_live_visibility($1,$2,$3,$4)',[u,e,c,visible]);
  await toggle(false);
  await db.exec('set role anon');
  for(const table of ['provisional_live_results','manual_live_entries','live_tracking','manual_live_tracking','live_combined_order','live_manual_only_order'])assert.equal((await db.query(`select * from ${table}`)).rows.length,0,table);
  assert.equal((await db.query<{public_visible:boolean}>('select public_visible from live_result_starts where class_id=$1',[c])).rows[0].public_visible,false);
  await assert.rejects(toggle(true));
  await db.exec('reset role');
  assert.equal((await db.query('select * from provisional_live_results')).rows.length,1);
  assert.equal((await db.query('select * from manual_live_entries')).rows.length,1);
  assert.equal((await db.query<{public_visible:boolean}>('select public_visible from live_result_starts where class_id=$1',[c2])).rows[0].public_visible,true);
  await toggle(true);
  await db.exec('set role anon');
  assert.equal((await db.query('select * from provisional_live_results')).rows.length,1);
  assert.equal((await db.query('select * from manual_live_entries')).rows.length,1);
  await db.exec('reset role');
  await db.query('delete from external_event_assignments where user_id=$1',[u]); await assert.rejects(toggle(false));
  await db.close();
});

